import { test, expect } from "./fixtures/pilot";
import AxeBuilder from "@axe-core/playwright";

test("owner confirms archive and students can read but cannot submit to an archived open assignment", async ({ page, pilot }, testInfo) => {
  await pilot.login(pilot.student);
  await page.goto(`/classrooms/${pilot.classroomId}`);
  await expect(page.getByRole("heading", { name: "SDPX · Browser test" })).toBeVisible();
  await expect(page.getByTestId("archive-classroom")).toHaveCount(0);
  await pilot.login(pilot.owner);
  await page.reload();
  const archive = page.getByTestId("archive-classroom");
  await archive.click();
  await expect(page.getByTestId("archive-cancel")).toBeFocused();
  await expect(page.getByTestId("archive-confirm")).toBeDisabled();
  await page.keyboard.press("Escape");
  await expect(archive).toBeFocused();
  await archive.click();
  await page.getByTestId("archive-name").fill("SDPX · Browser test");
  await page.getByTestId("archive-reason").fill("จบการทดสอบ เก็บข้อมูลไว้ตรวจสอบ");
  expect((await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21aa"]).analyze()).violations).toEqual([]);
  await page.screenshot({ path: testInfo.outputPath("archive-confirmation.png"), fullPage: true });
  await page.getByTestId("archive-confirm").click();
  await expect(page.getByTestId("archived-notice")).toBeVisible();
  await expect(archive).toHaveCount(0);
  await expect(page.getByTestId("roster-upload")).toBeDisabled();
  await page.goto("/dashboard");
  await expect(page.getByTestId("archived-classrooms")).toBeVisible();
  await expect(page.locator(`a.card-link[href="/classrooms/${pilot.classroomId}"]`)).toHaveCount(0);
  await page.getByTestId("archived-classrooms").locator("summary").click();
  await expect(page.getByTestId(`archived-room-${pilot.classroomId}`)).toBeVisible();
  await pilot.login(pilot.student);
  await page.goto(`/assignments/${pilot.assignmentId}`);
  await expect(page.getByTestId("archived-notice")).toBeVisible();
  await page.getByRole("tab", { name: "ประเมินกลุ่ม", exact: true }).click();
  await expect(page.getByTestId("submit-evaluations-btn")).toBeDisabled();
  await expect(page.getByTestId("choice-1")).toBeDisabled();
  const response = await page.request.post(`/api/assignments/${pilot.assignmentId}/submissions`, { headers: { origin: "http://localhost:3100", "Idempotency-Key": "archived-browser" }, data: { side: "GROUP" } });
  expect(response.status()).toBe(409);
  expect((await response.json()).error.code).toBe("CLASSROOM_ARCHIVED");
});
